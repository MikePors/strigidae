// keysReferencePath is docs/keys.md, relative to this package.
const keysReferencePath = "../../docs/keys.md"

// regenerateKeysReference is the command the stale-page failure prints.
const regenerateKeysReference = "make keys-docs"

// referenceGroup is one table of the reference: the actions of one view.
type referenceGroup struct {
	title       string
	description string
	actions     []keys.Action
}

// referenceGroups lists, in reading order, every action the reference covers.
// This cmd package is the one that imports every view, so a new view that
// declares actions adds one group here (the test below fails until it does,
// see TestKeysReferenceCoversEveryViewAction).
func referenceGroups() []referenceGroup {
	global := keys.DefaultGlobal()
	return []referenceGroup{
		{"All views", "Movement, search and help keys every view shares.", global.Actions()},
		{"Pull request list", "The repository's open pull requests (`strig` in a checkout, or `-R owner/name`).", pullrequestlist.Actions()},
		{"Dashboard", "The tabs of sections (`strig` outside a checkout, or with no GitHub remote).", dashboard.Actions()},
		{"Pull request workspace", "An open pull request: Overview, Files and Comments panes, and the diff.", workspace.Actions()},
		{"Diff pane", "Inside the pull request workspace, while the diff has focus.", workspace.DiffActions()},
	}
}

// escapeCell keeps text from ending a Markdown table cell.
func escapeCell(text string) string {
	return strings.ReplaceAll(text, "|", `\|`)
}

// keysCell shows an action's keys, each as code; a sequence is space-separated.
func keysCell(action keys.Action) string {
	if action.Binding == nil || len(action.Binding.Keys()) == 0 {
		return "none"
	}
	var shown []string
	for _, pressed := range action.Binding.Keys() {
		shown = append(shown, "`"+pressed+"`")
	}
	return strings.Join(shown, ", ")
}

func commandCell(command string) string {
	if command == "" {
		return ""
	}
	return "`:" + command + "`"
}

func writeActionTable(builder *strings.Builder, group referenceGroup) {
	fmt.Fprintf(builder, "## %s\n\n%s\n\n", group.title, group.description)
	builder.WriteString("| Action | Keys | Command | Description |\n|---|---|---|---|\n")
	for _, action := range group.actions {
		fmt.Fprintf(builder, "| `%s` | %s | %s | %s |\n", action.Name, keysCell(action), commandCell(action.Command), escapeCell(action.Help()))
	}
	builder.WriteString("\n")
}

// buildKeysReference renders docs/keys.md from the registries.
func buildKeysReference() string {
	var builder strings.Builder
	builder.WriteString("<!-- Generated by `" + regenerateKeysReference + "`. Do not edit by hand. -->\n\n")
	builder.WriteString("# Keys and commands\n\n")
	builder.WriteString("Every action strig has, the view it belongs to, its default keys and its help text, read from the same registries the help overlay (`?`) uses. A multi-key sequence is written with spaces (`g g` means `g` then `g`); `ctrl+d` is the control key; a shifted letter is the letter itself (`G`).\n\n")
	builder.WriteString("An action's name is the stable name it keeps whatever its keys are. A name that appears in more than one view (`next-tab`, `next-section`, `copy-url`) is the same action there. A command runs from the command line (`:` then `enter`); an action with no keys is reached only by its command.\n\n")
	for _, group := range referenceGroups() {
		writeActionTable(&builder, group)
	}
	builder.WriteString("## Commands of every view\n\n")
	builder.WriteString("These work on any view. A command of a single view is in that view's table above, and a plugin from the config's `plugins:` list is a command of the pull request workspace (see [plugins.md](plugins.md)).\n\n")
	builder.WriteString("| Command | Description |\n|---|---|\n")
	for _, command := range userinterface.CommandDescriptions() {
		var names []string
		for _, name := range command.Names {
			names = append(names, commandCell(name))
		}
		fmt.Fprintf(&builder, "| %s | %s |\n", strings.Join(names, ", "), escapeCell(command.Description))
	}
	builder.WriteString("\n## Also in the help overlay\n\n")
	builder.WriteString("These are documented in the help overlay but are not actions.\n\n| Keys | Meaning |\n|---|---|\n")
	global := keys.DefaultGlobal()
	for _, binding := range []keys.Action{{Binding: &global.Count}, {Binding: &global.Complete}} {
		fmt.Fprintf(&builder, "| `%s` | %s |\n", binding.Binding.Help().Key, escapeCell(binding.Help()))
	}
	return builder.String()
}

// TestKeysReferenceIsCurrent fails when docs/keys.md is stale. Regenerate it
// with `make keys-docs` (or `make golden`, which regenerates every generated
// file) and read the diff before committing.
func TestKeysReferenceIsCurrent(test *testing.T) {
	got := buildKeysReference()
	if os.Getenv("UPDATE_KEYS_DOCS") != "" || os.Getenv("UPDATE_GOLDEN") != "" {
		if err := os.WriteFile(keysReferencePath, []byte(got), 0o644); err != nil {
			test.Fatal(err)
		}
	}
	want, err := os.ReadFile(keysReferencePath)
	if err != nil {
		test.Fatalf("read docs/keys.md (run `%s` to create it): %v", regenerateKeysReference, err)
	}
	if diff := cmp.Diff(string(want), got); diff != "" {
		test.Errorf("docs/keys.md is out of date; run `%s` and commit the result (-want +got):\n%s", regenerateKeysReference, diff)
	}
}

// Every registered action name and command, from the same sources the
// action-name check reads, is in the page.
func TestKeysReferenceCoversEveryViewAction(test *testing.T) {
	page := buildKeysReference()
	registered := map[string][]string{
		"workspace": workspace.ActionNames(),
		"dashboard": dashboard.ActionNames(),
		"list":      pullrequestlist.ActionNames(),
	}
	global := keys.DefaultGlobal()
	for _, action := range global.Actions() {
		registered["global"] = append(registered["global"], action.Name)
	}
	for view, names := range registered {
		for _, name := range names {
			if !strings.Contains(page, "| `"+name+"` |") {
				test.Errorf("%s action %q is missing from docs/keys.md; add its view to referenceGroups", view, name)
			}
		}
	}
	for _, names := range [][]string{workspace.Commands(), dashboard.Commands(), pullrequestlist.Commands(), userinterface.CommandNames()} {
		for _, name := range names {
			if !strings.Contains(page, "`:"+name+"`") {
				test.Errorf("command :%s is missing from docs/keys.md", name)
			}
		}
	}
}

// Every action in the page has help text, and a binding or a command, so no
// row is empty.
func TestKeysReferenceRowsAreComplete(test *testing.T) {
	for _, group := range referenceGroups() {
		for _, action := range group.actions {
			if action.Help() == "" {
				test.Errorf("%s action %q has no help text; give its binding help or the action a Description", group.title, action.Name)
			}
			if action.Binding == nil && action.Command == "" {
				test.Errorf("%s action %q has neither keys nor a command", group.title, action.Name)
			}
		}
	}
	for _, command := range userinterface.CommandDescriptions() {
		if command.Description == "" {
			test.Errorf("shell command :%s has no description", command.Names[0])
		}
	}
}

func TestKeysReferenceCells(test *testing.T) {
	global := keys.DefaultGlobal()
	if got, want := keysCell(keys.Action{Binding: &global.Top}), "`g g`"; got != want {
		test.Errorf("sequence keys = %s, want %s", got, want)
	}
	pair := keys.Action{Binding: &global.Down}
	pair.Binding.SetKeys("j", "down")
	if got, want := keysCell(pair), "`j`, `down`"; got != want {
		test.Errorf("two keys = %s, want %s", got, want)
	}
	if got := keysCell(keys.Action{Name: "merge", Command: "merge"}); got != "none" {
		test.Errorf("no binding = %q, want none", got)
	}
	if got, want := escapeCell("a|b"), `a\|b`; got != want {
		test.Errorf("escapeCell = %s, want %s", got, want)
	}
}

// Rendering twice gives the same page: nothing in it depends on map order.
func TestKeysReferenceIsDeterministic(test *testing.T) {
	first := buildKeysReference()
	for range 5 {
		if diff := cmp.Diff(first, buildKeysReference()); diff != "" {
			test.Fatalf("page changed between renders (-first +later):\n%s", diff)
		}
	}
	if !slices.Contains(strings.Split(first, "\n"), "# Keys and commands") {
		test.Error("page has no title")
	}
}
